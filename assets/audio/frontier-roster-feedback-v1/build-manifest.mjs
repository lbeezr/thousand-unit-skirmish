// Preserve the first two increments; verify every original before assigning takes.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { validateAudioPack } from '../../../src/audio-assets.mjs';

const root = new URL('./', import.meta.url);
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
const original = await readFile(new URL('../runtime/frontier-feedback/v2/manifest.json', root));
if (sha256(original) !== 'ead2445947e811a451959325cd0f64de57ad7206db0947eca65c02576f1c3209') throw Error('Pinned second interaction manifest changed');
const manifest = JSON.parse(original);
manifest.version = 'v3';
const catalog = JSON.parse(await readFile(new URL('catalog.json', root), 'utf8'));
const bindings = manifest.pack.profiles.find(p => p.id === 'interactions').bindings;
const admitted = [];
for (const item of catalog.recordings) {
  const bytes = await readFile(new URL(`sources/${item.fileName}`, root));
  if (sha256(bytes) !== item.sha256 || bytes.length !== item.bytes) throw Error(`Original changed: ${item.fileName}`);
  if (!item.runtime) continue;
  if (manifest.pack.sources.some(s => s.id === item.id)) throw Error(`Duplicate source: ${item.id}`);
  manifest.pack.sources.push({ id: item.id, name: item.label, fileName: item.fileName, mimeType: 'audio/mpeg', tags: ['frontier', item.role, 'interaction'],
    provenance: { provider: 'ElevenLabs', model: item.model, generationId: item.generationId,
      prompt: item.prompt, createdAt: item.createdAt,
      ...(item.voiceId ? { attribution: `Voice ${item.voiceName} (${item.voiceId})` } : {}) } });
  const path = `assets/audio/frontier-roster-feedback-v1/sources/${item.fileName}`;
  admitted.push(path);
  manifest.downloads[item.id] = { path: `/${path}`, bytes: item.bytes, sha256: item.sha256, mimeType: 'audio/mpeg' };
  const binding = bindings[item.eventKey] ||= { bus: item.bus, priority: item.priority, cooldownMs: item.cooldownMs, variants: [] };
  binding.variants.push({ sourceId: item.id, gain: item.gain, caption: item.caption });
}
validateAudioPack(manifest.pack);
const output = new URL('../runtime/frontier-feedback/v3/', root);
await mkdir(output, { recursive: true });
const bytes = `${JSON.stringify(manifest, null, 2)}\n`;
await writeFile(new URL('manifest.json', output), bytes);
await writeFile(new URL('../../../src/server/roster-audio-sources.mjs', root),
  `// Generated by assets/audio/frontier-roster-feedback-v1/build-manifest.mjs.\n// Exact runtime selections; preserved comparisons and provenance stay private.\nexport const ROSTER_AUDIO_SOURCES = new Set(${JSON.stringify(admitted.sort(), null, 2)});\n`);
process.stdout.write(`${JSON.stringify({ packId: 'frontier-feedback', profileId: 'interactions', version: 'v3', sha256: sha256(bytes), sources: manifest.pack.sources.length, bindings: Object.keys(bindings).length, sourceBytes: Object.values(manifest.downloads).reduce((n, d) => n + d.bytes, 0) })}\n`);
